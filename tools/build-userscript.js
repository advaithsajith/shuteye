/*
 * Builds the no-Mac version of ShutEye into docs/ (ready for GitHub Pages):
 *
 *   docs/shuteye.user.js   the whole extension as one userscript
 *   docs/index.html        the install page
 *   docs/reader/           the dark PDF reader as a web page
 *
 * Run:  node tools/build-userscript.js
 * The userscript is assembled from the same files the Safari extension uses,
 * so there is only one copy of the code to maintain.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const EXT = path.join(ROOT, 'extension');
const SRC = path.join(ROOT, 'userscript');
const OUT = path.join(ROOT, 'docs');
const read = (dir, name) => fs.readFileSync(path.join(dir, name), 'utf8');
const VERSION = JSON.parse(read(EXT, 'manifest.json')).version;

function must(text, pattern, what) {
  if (typeof pattern === 'string' ? text.indexOf(pattern) < 0 : !pattern.test(text)) throw new Error('build: could not find ' + what);
}

/* ---------- The extension code, pointed at a private scope instead of the page's globals ---------- */

let shared = read(EXT, 'shared.js');
must(shared, '})(globalThis);', 'the end of shared.js');
shared = shared.replace('})(globalThis);', '})(SCOPE);');

let content = read(EXT, 'content.js');
must(content, 'globalThis.ShutEye', 'ShutEye in content.js');
content = content.replace(/globalThis\./g, 'SCOPE.');

let panelJs = read(EXT, 'popup.js');
must(panelJs, '})(globalThis);', 'the end of popup.js');
panelJs = panelJs.replace('})(globalThis);', '})(SCOPE);');

/* ---------- The panel's markup and styles, adapted to live in a shadow root ---------- */

const popupHtml = read(EXT, 'popup.html');
const bodyStart = popupHtml.indexOf('<body>'), bodyEnd = popupHtml.indexOf('<script src="shared.js">');
if (bodyStart < 0 || bodyEnd < 0) throw new Error('build: popup.html layout changed');
const panelHtml = popupHtml.slice(bodyStart + 6, bodyEnd).replace(/<!--[\s\S]*?-->/g, '').replace(/\n\s+/g, '\n').trim();

let panelCss = read(EXT, 'popup.css');
must(panelCss, /:root \{[^}]*\}/, 'the :root block in popup.css');
must(panelCss, /^html \{[^}]*\}/m, 'the html rule in popup.css');
panelCss = panelCss
  .replace(/:root \{[^}]*\}/, '')                         // colours come from the host element instead
  .replace(/^html \{[^}]*\}/m, '')
  .replace(/(^|[\s,}])body(?=[\s.{])/gm, '$1.se-wrap');   // the popup's <body> becomes the sheet's wrapper

// Where the built files are published. Userscripts uses this to offer updates.
const SITE = 'https://advaithsajith.github.io/shuteye/';

const banner = `// ==UserScript==
// @name         ShutEye
// @description  Dark mode for every website, in your own theme. Tap the fox to change it.
// @version      ${VERSION}
// @match        *://*/*
// @updateURL    ${SITE}shuteye.meta.js
// @downloadURL  ${SITE}shuteye.user.js
// @run-at       document-start
// @inject-into  content
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM_getValue
// @grant        GM_setValue
// ==/UserScript==

/*
 * ShutEye ${VERSION} (userscript build). Copyright (c) 2026 Advaith Sajith. MIT licence.
 * This file is generated by tools/build-userscript.js. Edit the files in
 * extension/ and userscript/, then run the build again.
 */
`;

const script = banner + `(function () {
'use strict';

${read(SRC, 'adapter.js')}
const SCOPE = { __shuteyeEmbed: true, __shuteyeApi: makeApi() };

/* ===== extension/shared.js ===== */
${shared}
/* ===== extension/content.js ===== */
${content}
/* ===== extension/popup.js ===== */
${panelJs}
/* ===== userscript/ui.js ===== */
${read(SRC, 'ui.js')}
startUi(SCOPE, ${JSON.stringify(panelHtml)}, ${JSON.stringify(panelCss)}, ${JSON.stringify(read(SRC, 'ui.css'))}, ${JSON.stringify(VERSION)});
})();
`;

fs.mkdirSync(path.join(OUT, 'reader', 'vendor'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'shuteye.user.js'), script);
// A tiny copy of just the header: update checks read this instead of the whole script.
fs.writeFileSync(path.join(OUT, 'shuteye.meta.js'), banner.slice(0, banner.indexOf('// ==/UserScript==') + 18) + '\n');

/* ---------- The web PDF reader ---------- */

let reader = read(EXT, 'reader.html');
must(reader, '<script src="shared.js"></script>', 'shared.js in reader.html');
reader = reader
  .replace('<html lang="en">', '<html lang="en" data-shuteye-own>')
  .replace('<meta name="color-scheme" content="dark">', '<meta name="color-scheme" content="dark">\n  <meta name="shuteye-site" content="../">')
  .replace('<script src="shared.js"></script>', '<script src="web-api.js"></script>\n  <script src="shared.js"></script>');
fs.writeFileSync(path.join(OUT, 'reader', 'index.html'), reader);
for (const f of ['reader.css', 'reader.js', 'shared.js']) fs.copyFileSync(path.join(EXT, f), path.join(OUT, 'reader', f));
fs.copyFileSync(path.join(SRC, 'web-api.js'), path.join(OUT, 'reader', 'web-api.js'));
for (const f of fs.readdirSync(path.join(EXT, 'vendor'))) fs.copyFileSync(path.join(EXT, 'vendor', f), path.join(OUT, 'reader', 'vendor', f));

/* ---------- The install page ---------- */

globalThis.chrome = { storage: {} };
require(path.join(EXT, 'shared.js'));
const S = globalThis.ShutEye;
const page = read(SRC, 'install.html')
  .replace(/<!--FOX-->/g, S.foxSvg())
  .replace('<!--THEMES-->', S.THEMES.map((t) =>
    `<li style="background:${t.bg};color:${t.fg};border-color:${t.accent}"><i style="background:${t.accent}"></i>${t.name}</li>`).join(''))
  .replace(/<!--VERSION-->/g, VERSION);
fs.writeFileSync(path.join(OUT, 'index.html'), page);
fs.copyFileSync(path.join(EXT, 'images', 'icon-256.png'), path.join(OUT, 'icon.png'));
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');

console.log('built docs/shuteye.user.js (' + Math.round(script.length / 1024) + ' KB), docs/index.html, docs/reader/');
